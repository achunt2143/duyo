import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import {
  ViewCodes,
  findViews,
  generateTypes,
  handlersOf,
  namedOf,
  syncViewTypes,
  typesPathFor,
  validateSpec,
} from '../index.js';

const settings = {
  name: 'App.Settings',
  kind: 'duyo.FittableRows',
  handlers: { onLog: 'appendLog' },
  components: [
    { kind: 'mochi.Header', content: 'Settings' },
    {
      kind: 'duyo.FittableColumns',
      components: [
        { kind: 'mochi.Toggle', name: 'wifi', onChange: 'wifiChanged' },
        { kind: 'mochi.Button', name: 'save', ontap: 'save' },
        { kind: 'mochi.Button', name: 'search', ontap: 'customer.search' },
      ],
    },
    { name: 'status' },
  ],
};

const codes = (spec: unknown) => validateSpec(spec).map((d) => d.code);

describe('reading a spec', () => {
  it('finds named components at any depth, with their kinds', () => {
    expect(namedOf(settings)).toEqual([
      ['wifi', 'mochi.Toggle'],
      ['save', 'mochi.Button'],
      ['search', 'mochi.Button'],
      ['status', 'duyo.Control'],
    ]);
  });

  it('finds the handlers the code-behind must implement, leaving actions to the runtime', () => {
    expect(handlersOf(settings)).toEqual(['appendLog', 'save', 'wifiChanged']);
  });
});

describe('validateSpec', () => {
  it('accepts a well-formed spec', () => {
    expect(validateSpec(settings)).toEqual([]);
  });

  it('requires an object with a name', () => {
    expect(codes([])).toEqual([ViewCodes.NOT_OBJECT]);
    expect(codes({ components: [] })).toEqual([ViewCodes.NAME]);
  });

  it('rejects duplicate names across the whole view, with both paths', () => {
    const problems = validateSpec({
      name: 'X',
      components: [{ name: 'a' }, { components: [{ name: 'a' }] }],
    });
    expect(problems.map((p) => p.code)).toEqual([ViewCodes.DUPLICATE_NAME]);
    expect(problems[0]!.path).toBe('$.components[1].components[0].name');
    expect(problems[0]!.message).toContain('$.components[0]');
  });

  it('rejects on… properties that are not method or action names', () => {
    expect(codes({ name: 'X', components: [{ ontap: 'save it' }] })).toEqual([ViewCodes.BAD_HANDLER]);
    expect(codes({ name: 'X', components: [{ onContent: 3 }] })).toEqual([ViewCodes.BAD_HANDLER]);
    expect(codes({ name: 'X', components: [{ ontap: 'customer.search' }] })).toEqual([]);
  });

  it('rejects prototype-polluting keys anywhere', () => {
    const spec = JSON.parse('{"name":"X","components":[{"published":{"__proto__":{"x":1}}}]}');
    expect(codes(spec)).toContain(ViewCodes.UNSAFE_KEY);
  });

  it('rejects malformed components and kinds', () => {
    expect(codes({ name: 'X', components: {} })).toEqual([ViewCodes.COMPONENTS]);
    expect(codes({ name: 'X', components: [{ kind: 3 }] })).toEqual([ViewCodes.BAD_KIND]);
  });
});

describe('generateTypes', () => {
  const text = generateTypes(settings, 'Settings.view.json');

  it('names the source and imports only types from @duyo/core', () => {
    expect(text).toMatch(/^\/\/ Generated by @duyo\/views from Settings\.view\.json/);
    expect(text).toContain("import type { Component, ComponentEvent, Instance, ViewComponent } from '@duyo/core';");
  });

  it('types this.$ with every named component and its kind', () => {
    expect(text).toContain('  /** mochi.Toggle */\n  wifi: Instance<"mochi.Toggle">;');
    expect(text).toContain('  status: Instance<"duyo.Control">;');
  });

  it('lists the handlers the code-behind must implement', () => {
    expect(text).toContain("export type Handlers = 'appendLog' | 'save' | 'wifiChanged';");
  });

  it('copes with a view that names nothing', () => {
    const empty = generateTypes({ name: 'X' }, 'X.view.json');
    expect(empty).toContain('export type Named = {};');
    expect(empty).toContain('export type Handlers = never;');
  });

  it('quotes names that are not identifiers', () => {
    expect(generateTypes({ name: 'X', components: [{ name: 'save-button' }] }, 'X.view.json')).toContain('"save-button": Instance<"duyo.Control">;');
  });
});

describe('syncing files', () => {
  let dir = '';
  afterEach(() => {
    if (dir) rmSync(dir, { recursive: true, force: true });
  });

  const scaffold = () => {
    dir = mkdtempSync(join(tmpdir(), 'duyo-views-'));
    const file = join(dir, 'Settings.view.json');
    writeFileSync(file, JSON.stringify(settings));
    return file;
  };

  it('writes the types beside the spec, then reports no change', () => {
    const file = scaffold();
    expect(syncViewTypes(file).changed).toBe(true);
    expect(readFileSync(typesPathFor(file), 'utf8')).toContain("'wifiChanged'");
    expect(syncViewTypes(file).changed).toBe(false);
    expect(findViews(dir)).toEqual([file]);
  });

  it('check mode reports a stale file without writing it', () => {
    const file = scaffold();
    syncViewTypes(file);
    writeFileSync(file, JSON.stringify({ ...settings, components: [{ name: 'only', ontap: 'go' }] }));
    const result = syncViewTypes(file, { check: true });
    expect(result.changed).toBe(true);
    expect(readFileSync(typesPathFor(file), 'utf8')).toContain("'wifiChanged'");
  });

  it('writes nothing while the spec is invalid', () => {
    const file = scaffold();
    writeFileSync(file, '{ "name": "X", "components": [ ');
    const result = syncViewTypes(file);
    expect(result.diagnostics.map((d) => d.code)).toEqual([ViewCodes.PARSE]);
    expect(result.changed).toBe(false);
  });

  it('the CLI exits non-zero on a stale or invalid view in --check mode', () => {
    const file = scaffold();
    const cli = resolve(__dirname, '../../bin/duyo-views.js');
    const run = (...args: string[]) => spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8' });

    expect(run(dir, '--check').status).toBe(1);
    expect(run(dir).status).toBe(0);
    expect(run(dir, '--check').status).toBe(0);

    writeFileSync(file, JSON.stringify({ name: 'X', components: [{ ontap: 'not valid' }] }));
    const bad = run(dir, '--check');
    expect(bad.status).toBe(1);
    expect(bad.stderr).toContain(ViewCodes.BAD_HANDLER);
  });
});
